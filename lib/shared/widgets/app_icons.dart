/// Named-icon lookup for the whole app.
///
/// Icons are referenced by name from `core/constants/enums.dart` so domain
/// enums stay free of any icon-package dependency, and every screen keeps a
/// single icon family (plan §7.7). Unknown names degrade to a neutral circle
/// rather than throwing (plan §8 tolerant parsing).
abstract final class AppIcons {
  const AppIcons._();

  static IconData byName(String name) => table[name] ?? LucideIcons.circle;

  static bool has(String name) => table.containsKey(name);

  /// Number of registered names — asserted by a unit test so a typo in a
  /// screen or enum fails loudly rather than rendering a blank circle.
  static int get length => table.length;
}

